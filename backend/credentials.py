"""Server-side encryption for credentials owned by individual accounts."""

import os
import tempfile
from pathlib import Path

from cryptography.fernet import Fernet, InvalidToken

from .database import connect
from .storage import StoreError

MASTER_ENV = 'LEXIVAULT_CREDENTIALS_KEY'
MASTER_FILENAME = '.lexivault-credentials.key'


class CredentialVault:
    def __init__(self, accounts_path):
        self.database = accounts_path
        self.master_path = accounts_path.with_name(MASTER_FILENAME)

    def _read_local_master(self):
        if self.master_path.is_symlink():
            raise StoreError('凭据主密钥文件不能是符号链接。', 503)
        return self.master_path.read_bytes().strip()

    def _create_local_master(self):
        # Publish a full key atomically without replacing one generated by another process.
        descriptor, name = tempfile.mkstemp(prefix='.lv-credentials-', dir=self.master_path.parent)
        temporary = Path(name)
        try:
            with os.fdopen(descriptor, 'wb') as output:
                output.write(Fernet.generate_key())
                output.flush()
                os.fsync(output.fileno())
            try:
                os.link(temporary, self.master_path)
            except FileExistsError:
                pass
            return self._read_local_master()
        finally:
            temporary.unlink(missing_ok=True)

    def _cipher(self, create=False):
        configured = os.environ.get(MASTER_ENV)
        if configured is not None:
            master = configured.strip()
        else:
            try:
                try:
                    master = self._read_local_master()
                except FileNotFoundError:
                    with connect(self.database) as db:
                        has_credentials = db.execute('SELECT 1 FROM openalex_credentials LIMIT 1').fetchone()
                    if self.master_path.exists():
                        master = self._read_local_master()
                    elif not create or has_credentials:
                        raise StoreError('缺少凭据主密钥，请恢复原主密钥后重试。', 503)
                    else:
                        master = self._create_local_master()
            except OSError as error:
                raise StoreError('无法读取或保存凭据主密钥，请检查后端配置目录。', 503) from error
        try:
            return Fernet(master)
        except (ValueError, UnicodeError) as error:
            raise StoreError(f'凭据主密钥格式有误，请检查 {MASTER_ENV} 或本地密钥文件。', 503) from error

    @staticmethod
    def _context(user_id):
        return f'openalex\0{user_id}\0'.encode()

    def configured(self, user_id):
        with connect(self.database) as db:
            return db.execute('SELECT 1 FROM openalex_credentials WHERE user_id=?', (user_id,)).fetchone() is not None

    def openalex_key(self, user_id):
        with connect(self.database) as db:
            row = db.execute('SELECT ciphertext FROM openalex_credentials WHERE user_id=?', (user_id,)).fetchone()
        if row is None:
            return None
        try:
            decrypted = self._cipher().decrypt(row['ciphertext'])
            context = self._context(user_id)
            if not decrypted.startswith(context):
                raise InvalidToken
            return decrypted[len(context):].decode('ascii')
        except (InvalidToken, UnicodeDecodeError, TypeError) as error:
            raise StoreError('无法解密此账号的 OpenAlex Key，请检查原主密钥，或移除后重新绑定。', 503) from error

    def save_openalex(self, user_id, key):
        if self.configured(user_id):
            self.openalex_key(user_id)
        ciphertext = self._cipher(create=True).encrypt(self._context(user_id) + key.encode('ascii'))
        with connect(self.database) as db:
            db.execute("""INSERT INTO openalex_credentials(user_id,ciphertext) VALUES(?,?)
                          ON CONFLICT(user_id) DO UPDATE SET ciphertext=excluded.ciphertext""", (user_id, ciphertext))

    def remove_openalex(self, user_id):
        with connect(self.database) as db:
            db.execute('DELETE FROM openalex_credentials WHERE user_id=?', (user_id,))
